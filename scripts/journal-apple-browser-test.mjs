// Apple 兼容修复定向闭环；必须显式指定本轮隔离库，禁止写人工验收库。
import assert from 'node:assert/strict';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { pathToFileURL } from 'node:url';
const base = process.env.JOURNAL_TEST_BASE;
assert.match(base || '', /^http:\/\/127\.0\.0\.1:\d+$/);
const health = await fetch(`${base}/health`);
const database = process.env.JOURNAL_TEST_DATABASE;
assert.match(database || '', /^pantry_nook_test_[a-f0-9]{32}$/);
assert.equal(health.headers.get('x-pantry-nook-test-database'), database);
assert.equal(health.headers.get('x-pantry-nook-test-media'), database);
const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href);
const samples = resolve(process.env.JOURNAL_SAMPLES);
const output = resolve('.review/apple-browser');
await mkdir(output, { recursive: true });
const browser = await chromium.launch();
const page = await browser.newPage();
page.setDefaultTimeout(60000);
const crashes = [], checks = [];
page.on('pageerror', error => crashes.push(error.message));
const caption = `Apple 恢复验证 ${Date.now()}`;
const article = () => page.locator('.journal-sheet').filter({ hasText: caption });
const current = async () => (await (await fetch(`${base}/api/journal/entries?limit=100&offset=0`)).json()).data.find(item => item.caption === caption);
const save = async edit => {
  await page.getByRole('button', { name: edit ? '保存修改' : '保存这一餐', exact: true }).click();
  await page.locator('dialog').waitFor({ state: 'detached' });
};
try {
  await page.goto(base);
  await page.getByRole('button', { name: '手记', exact: true }).click();
  await page.getByRole('button', { name: '＋ 记下一餐', exact: true }).first().click();
  await page.getByRole('button', { name: 'Apple 实况怎么上传？', exact: true }).click();
  assert.equal(await page.locator('.journal-motion-help').getAttribute('open'), '');
  const choose = page.waitForEvent('filechooser');
  await page.getByRole('button', { name: '从文件添加原件', exact: true }).click();
  await (await choose).setFiles(join(samples, 'apple-iphone15.heic'));
  await page.getByRole('button', { name: '补充 MOV', exact: true }).waitFor();
  await page.locator('dialog textarea').fill(caption);
  await save(false);
  const before = await current();
  assert.equal(before.photos.length, 1);
  assert.equal(before.photos[0].live_status, 'missing_video');
  checks.push('文件原件入口可用；Apple照片缺MOV明确提示，可先保存静态照片');
  await article().getByRole('button', { name: '编辑', exact: true }).click();
  for (const [name, width, height] of [['phone', 390, 844], ['tablet', 834, 1112]]) {
    await page.setViewportSize({ width, height });
    await page.getByRole('button', { name: '怎么获取？', exact: true }).click();
    await page.screenshot({ path: join(output, `${name}-help.png`), fullPage: true });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    assert.ok(await page.locator('dialog').evaluate(el => el.scrollWidth <= el.clientWidth + 1));
  }
  const motion = page.waitForEvent('filechooser');
  await page.getByRole('button', { name: '补充 MOV', exact: true }).click();
  await (await motion).setFiles(join(samples, 'apple-iphone15.mov'));
  await page.getByText('◎ 实况已就绪', { exact: true }).waitFor();
  assert.equal(await page.locator('.journal-draft-photo').count(), 1);
  await save(true);
  const after = await current();
  assert.equal(after.photos.length, 1);
  assert.equal(after.photos[0].image.id, before.photos[0].image.id);
  assert.ok(after.photos[0].motion);
  assert.deepEqual(Buffer.from(await (await fetch(`${base}${after.photos[0].image.original_url}`)).arrayBuffer()), await readFile(join(samples, 'apple-iphone15.heic')));
  await article().getByRole('button', { name: '翻开这篇 ↗', exact: true }).click();
  await page.getByRole('button', { name: '◎ 播放实况', exact: true }).click();
  await page.waitForFunction(() => { const v = document.querySelector('.journal-viewer-video'); return v && !v.paused && v.currentTime > .1 && v.videoWidth > 0; });
  await page.getByRole('button', { name: '关闭照片', exact: true }).click();
  await page.locator('.pswp').waitFor({ state: 'detached' });
  checks.push('已保存照片编辑补MOV：仍为1张、原图ID和字节不变、真实视频可播放；手机和平板帮助无横向溢出');
  await page.getByRole('button', { name: '＋ 记下一餐', exact: true }).first().click();
  const raw = await readFile(resolve(process.env.JOURNAL_MPO_SAMPLE));
  await page.getByLabel('选择照片及实况视频', { exact: true }).setInputFiles({ name: 'mpf-photo.jpg', mimeType: 'image/jpeg', buffer: raw });
  await page.waitForFunction(() => document.querySelector('.journal-draft-photo')?.dataset.uploadId);
  await page.locator('dialog textarea').fill(`${caption} MPO`);
  await save(false);
  const mpo = (await (await fetch(`${base}/api/journal/entries?limit=100&offset=0`)).json()).data.find(item => item.caption === `${caption} MPO`);
  const original = await fetch(`${base}${mpo.photos[0].image.original_url}`);
  assert.match(original.headers.get('content-type'), /^image\/jpeg/);
  assert.deepEqual(Buffer.from(await original.arrayBuffer()), raw);
  assert.equal(mpo.photos[0].image.live_kind, 'still');
  assert.equal(mpo.photos[0].motion, null);
  checks.push('真实MPO/JPEG通过浏览器上传和保存，原件字节及JPEG MIME正确，不伪造实况');
  assert.deepEqual(crashes, []);
  await writeFile(join(output, 'result.json'), JSON.stringify({ database, checks, crashes }, null, 2));
  console.log(JSON.stringify({ checks, crashes }));
} catch (error) {
  await writeFile(join(output, 'failure.txt'), await page.locator('body').innerText());
  await page.screenshot({ path: join(output, 'failure.png'), fullPage: true });
  throw error;
} finally { await browser.close(); }
